// This file is the byte-identity harness for the signing-path optimizations
// (parallel tree building, reusing the root that the build already computed,
// FORS parallelism, and per-hash allocation cuts).
//
// Every one of those changes is supposed to be invisible in the signature
// bytes: same keys and same message must produce the same serialized
// signature, for every backend and variant, or a node running the new code
// and a node running the old code disagree about the same signature.
//
// The signatures below were generated by the PRE-optimization implementation
// and are asserted as literals. A mismatch means the optimization changed the
// output, which is a consensus-level change and must fail loudly rather than
// ship.
//
// RANDOMIZE=false is required: with randomization on, Spx_sign reads fresh
// entropy for OptRand, so no signature is reproducible.

// fixedKey builds a deterministic secret key from a label, so the golden
// vectors depend only on this test file and the construction — never on
// crypto/rand.
func fixedKey(t *testing.T, params *parameters.Parameters, label string) (*SPHINCS_SK, *SPHINCS_PK) {
	t.Helper()
	derive := func(tag string) []byte {
		sum := sha256.Sum256([]byte("sthincs-golden/" + label + "/" + tag))
		return sum[:params.N]
	}
	SKseed := derive("SKseed")
	SKprf := derive("SKprf")
	PKseed := derive("PKseed")

	PKroot, err := hypertree.Ht_PKgen(params, SKseed, PKseed)
	if err != nil {
		t.Fatalf("Ht_PKgen: %v", err)
	}
	sk := &SPHINCS_SK{SKseed: SKseed, SKprf: SKprf, PKseed: PKseed, PKroot: PKroot}
	pk := &SPHINCS_PK{PKseed: PKseed, PKroot: PKroot}
	return sk, pk
}

// goldenSignatures pins the pre-optimization signature bytes, captured from
// the sequential implementation before any of the signing-path changes landed.
//
// Format: "<set> <serialized length> <sha256 of serialized signature>".
// A mismatch here means the signature bytes changed, which is a
// consensus-level break: a node on the new code and a node on the old code
// would disagree about the same signature. Re-baseline ONLY for an
// intentional protocol change.
//
// RE-BASELINE (SPHINXHASH rows only): the three SPHINXHASH-* digests below were
// regenerated when the spxhash/v2 branch-`A` primitive changed from a double
// SHA-256 to a single SHA-512/256 (see src/spxhash/v2/README.md, "Changed
// (branch A)"). Only the SPHINXHASH backend routes through spxhash/v2, so the
// SHA256-* and SHAKE256-* digests are unchanged. Signature *lengths* are
// unchanged; only the bytes moved. This is the deliberate, documented protocol
// change permitted by the paragraph above.
