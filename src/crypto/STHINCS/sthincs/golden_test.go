// TestGoldenSignatures pins the signature bytes for every backend.
//
// The parallel tree build, the reuse of the root the build already computed,
// FORS parallelism and the per-hash allocation cuts are all required to be
// invisible here. If one of them is not, this fails.
func TestGoldenSignatures(t *testing.T) {
	constructors := []struct {
		name string
		make func(bool) *parameters.Parameters
	}{
		{"SHA256-128f-simple", parameters.MakeSthincsPlusSHA256128fSimple},
		{"SHA256-128f-robust", parameters.MakeSthincsPlusSHA256128fRobust},
		{"SHA256-128s-simple", parameters.MakeSthincsPlusSHA256128sSimple},
		{"SHA256-192f-simple", parameters.MakeSthincsPlusSHA256192fSimple},
		{"SHAKE256-128f-simple", parameters.MakeSthincsPlusSHAKE256128fSimple},
		{"SHAKE256-128f-robust", parameters.MakeSthincsPlusSHAKE256128fRobust},
		{"SPHINXHASH-128f-simple", parameters.MakeSthincsPlusSPHINXHASH128fSimple},
		{"SPHINXHASH-128f-robust", parameters.MakeSthincsPlusSPHINXHASH128fRobust},
		{"SPHINXHASH-192f-robust", parameters.MakeSthincsPlusSPHINXHASH192fRobust},
	}

	msg := []byte("sthincs-golden-signature")

	for _, tc := range constructors {
		t.Run(tc.name, func(t *testing.T) {
			want, ok := goldenSignatures[tc.name]
			if !ok {
				t.Fatalf("no golden vector pinned for %s", tc.name)
			}
			params := tc.make(false) // RANDOMIZE=false: reproducible bytes
			sk, pk := fixedKey(t, params, tc.name)

			sig, err := Spx_sign(params, msg, sk)
			if err != nil {
				t.Fatalf("Spx_sign: %v", err)
			}
			raw, err := sig.SerializeSignature()
			if err != nil {
				t.Fatalf("SerializeSignature: %v", err)
			}
			if !Spx_verify(params, msg, sig, pk) {
				t.Fatal("golden signature failed to verify")
			}
			if len(raw) != want.Len {
				t.Errorf("signature length = %d, want %d", len(raw), want.Len)
			}
			sum := hex.EncodeToString(func() []byte { s := sha256.Sum256(raw); return s[:] }())
			if sum != want.SigSHA256 {
				t.Errorf("signature bytes changed for %s\n  got  %s\n  want %s\n"+
					"This is a consensus-breaking change: nodes running different code would\n"+
					"disagree about the same signature. Revert the change, or re-baseline\n"+
					"deliberately if the protocol is meant to change.",
					tc.name, sum, want.SigSHA256)
			}
		})
	}
}

// TestTopTreeCacheIsValidatedAgainstTheKey checks the one place the top-layer
// cache could go wrong: if the key's seeds change (or are zeroed) without the
// cache being rebuilt, signing would use a root that no longer matches the
// seeds. The cache must be discarded and rebuilt rather than trusted.
func TestTopTreeCacheIsValidatedAgainstTheKey(t *testing.T) {
	params := parameters.MakeSthincsPlusSHA256128fSimple(false)
	sk, pk := fixedKey(t, params, "cache-validation")
	msg := []byte("cache-validation")

	// First sign populates the cache and must succeed.
	if _, err := Spx_sign(params, msg, sk); err != nil {
		t.Fatalf("Spx_sign (cold cache): %v", err)
	}
	if sk.topTree == nil {
		t.Fatal("expected the top layer to be cached after the first signature")
	}

	// A corrupted cache must not be trusted: force the cached root to differ
	// from PKroot and confirm signing still works, because topTreeFor
	// revalidates against the key's own seeds.
	sk.mu.Lock()
	sk.topTree = corruptedTreeCache(params)
	sk.mu.Unlock()

	sig, err := Spx_sign(params, msg, sk)
	if err != nil {
		t.Fatalf("Spx_sign with a stale cache: %v", err)
	}
	if !Spx_verify(params, msg, sig, pk) {
		t.Fatal("signature made with a rebuilt cache did not verify")
	}

	// Zeroize must release the cache: the key is spent.
	sk.Zeroize()
	if sk.topTree != nil {
		t.Error("Zeroize left the top-layer cache populated")
	}
}

// corruptedTreeCache returns a cache whose root does not match the key, to
// exercise the revalidation path in topTreeFor.
func corruptedTreeCache(params *parameters.Parameters) *xmss.Xmss_treeCache {
	adrs := new(address.ADRS)
	adrs.SetLayerAddress(params.D - 1)
	adrs.SetTreeAddress(0)
	c, err := xmss.Xmss_cacheLeaves(params, make([]byte, params.N), make([]byte, params.N), adrs)
	if err != nil {
		panic(err)
	}
	return c
}

// TestConcurrentSigningOnOneKey exercises signing from several goroutines with
// the same SPHINCS_SK, which the top-layer cache has to tolerate: the cache is
// lazily populated and then shared, so populating it twice concurrently is a
// data race unless it is guarded.
//
// Run under -race for this to be worth anything.
func TestConcurrentSigningOnOneKey(t *testing.T) {
	for _, ctor := range []func(bool) *parameters.Parameters{
		parameters.MakeSthincsPlusSHA256128fSimple,
		parameters.MakeSthincsPlusSHA256128fRobust,
		parameters.MakeSthincsPlusSHAKE256128fRobust,
		parameters.MakeSthincsPlusSPHINXHASH128fSimple,
		parameters.MakeSthincsPlusSPHINXHASH128fRobust,
	} {
		params := ctor(false)
		sk, pk := fixedKey(t, params, "concurrent")

		const goroutines = 8
		var wg sync.WaitGroup
		errCh := make(chan error, goroutines)
		for i := 0; i < goroutines; i++ {
			wg.Add(1)
			go func(i int) {
				defer wg.Done()
				// Distinct messages, so a mix-up between goroutines would
				// produce a signature that does not verify.
				msg := fmt.Appendf(nil, "concurrent-probe-%d", i)
				sig, err := Spx_sign(params, msg, sk)
				if err != nil {
					errCh <- fmt.Errorf("goroutine %d: Spx_sign: %w", i, err)
					return
				}
				if !Spx_verify(params, msg, sig, pk) {
					errCh <- fmt.Errorf("goroutine %d: signature did not verify", i)
				}
			}(i)
		}
		wg.Wait()
		close(errCh)
		for err := range errCh {
			t.Error(err)
		}
	}
}

// TestSigningIsDeterministicAndOrderIndependent checks the two properties the
// parallel implementation must preserve, independent of the pinned vectors:
//
//  1. Signing the same message twice yields identical bytes (no map iteration
//     order, no goroutine scheduling, leaking into the output).
//  2. A signature made under a different key does not verify, and vice versa.
func TestSigningIsDeterministicAndOrderIndependent(t *testing.T) {
	for _, ctor := range []func(bool) *parameters.Parameters{
		parameters.MakeSthincsPlusSHA256128fSimple,
		parameters.MakeSthincsPlusSHA256128fRobust,
		parameters.MakeSthincsPlusSHAKE256128fRobust,
		parameters.MakeSthincsPlusSPHINXHASH128fSimple,
		parameters.MakeSthincsPlusSPHINXHASH128fRobust,
	} {
		params := ctor(false)
		sk, pk := fixedKey(t, params, "determinism")
		other, _ := fixedKey(t, params, "determinism-other")

		msg := []byte("determinism-probe")
		a, err := Spx_sign(params, msg, sk)
		if err != nil {
			t.Fatalf("Spx_sign a: %v", err)
		}
		ra, err := a.SerializeSignature()
		if err != nil {
			t.Fatal(err)
		}

		// Repeat several times: with a parallel tree build, a shared
		// non-thread-safe buffer would show up as intermittent corruption,
		// so a single repeat is not enough evidence.
		for i := 0; i < 4; i++ {
			b, err := Spx_sign(params, msg, sk)
			if err != nil {
				t.Fatalf("Spx_sign b (%d): %v", i, err)
			}
			rb, err := b.SerializeSignature()
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(ra, rb) {
				t.Fatalf("signing is not deterministic: repeat %d differs from the first signature", i)
			}
		}

		if !Spx_verify(params, msg, a, pk) {
			t.Fatal("own signature did not verify")
		}
		if Spx_verify(params, msg, a, &SPHINCS_PK{PKseed: other.PKseed, PKroot: other.PKroot}) {
			t.Fatal("signature verified under a different public key")
		}
		if Spx_verify(params, []byte("different message"), a, pk) {
			t.Fatal("signature verified under a different message")
		}
	}
}
